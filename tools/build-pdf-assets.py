"""Builds src/configurator-pdf-assets.js (the PDF's fonts and Coastal's logo as data URLs), the page
fonts public/assets/fonts/lato-400.woff2 and lato-700.woff2, the logo for the header, and the
favicon and touch icon.

python3 tools/build-pdf-assets.py

Fonts: Lato 2.015 (OFL; the font coastalgardenbuildings.co.uk sets for body and headings), from
the TTFs in src/assets-src, subset to Latin with the PDF's and the page's symbols
(£ × ° ² – − ’ “ ” …). Lato 2 has the true minus sign the price lines use.
Logo: Coastal's own logo as published (coastal_block_blue-01.jpg, white script on its blue-grey
block, 628 x 428), not redrawn. The block carries its own background, so the PDF uses the same
image on light and dark pages.
"""
import base64
import io
import json
from pathlib import Path
from PIL import Image
from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'src' / 'assets-src'
PUB = ROOT / 'public'
TEXT = ''.join(chr(c) for c in range(0x20, 0x7f)) + '£×°²–—−’‘“”…•·éèêáàâíóôúüçñ€½¼¾→'


def sub(path, flavor=None):
    font = TTFont(path)
    opts = subset.Options(); opts.layout_features = ['kern', 'liga', 'tnum', 'lnum']; opts.name_IDs = ['*']; opts.notdef_outline = True
    if flavor:
        opts.flavor = flavor
    s = subset.Subsetter(opts); s.populate(text=TEXT); s.subset(font)
    font.flavor = flavor
    out = io.BytesIO(); font.save(out)
    return out.getvalue()


regular, bold = SRC / 'Lato-Regular.ttf', SRC / 'Lato-Bold.ttf'
# jsPDF knows four styles per family: 'heading' (the italic slot) carries Lato Bold too.
fonts = {k: base64.b64encode(sub(p)).decode() for k, p in {'regular': regular, 'heading': bold, 'bold': bold}.items()}

logo = Image.open(SRC / 'coastal-logo.jpg').convert('RGB')
buf = io.BytesIO(); logo.save(buf, format='JPEG', quality=90)
logo_url = 'data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()
js = ('// Generated by tools/build-pdf-assets.py: do not edit.\n'
      f'export const PDF_FONTS = {json.dumps(fonts)};\n'
      f'export const PDF_LOGO = {json.dumps(logo_url)};\n'
      f'export const PDF_LOGO_SIZE = {json.dumps(list(logo.size))};\n'
      'export const PDF_LOGO_WHITE = PDF_LOGO;\n'
      'export const PDF_LOGO_WHITE_SIZE = PDF_LOGO_SIZE;\n')
(ROOT / 'src' / 'configurator-pdf-assets.js').write_text(js)

# Page fonts.
(PUB / 'assets' / 'fonts').mkdir(parents=True, exist_ok=True)
for weight, path in [(400, regular), (700, bold)]:
    (PUB / 'assets' / 'fonts' / f'lato-{weight}.woff2').write_bytes(sub(path, 'woff2'))

# Header logo: 2x for a 48px-high slot.
(PUB / 'assets' / 'brand').mkdir(parents=True, exist_ok=True)
h = 112
logo.resize((round(logo.width * h / logo.height), h), Image.Resampling.LANCZOS).save(PUB / 'assets' / 'brand' / 'coastal-logo.webp', quality=88, method=6)

# Favicon and touch icon: the "C" of Coastal's script on its blue-grey, cropped from the logo.
letter = logo.crop((30, 62, 152, 272))  # the C alone (the o starts at about x 155)
c = Image.new('RGB', (230, 230), logo.getpixel((5, 5)))
c.paste(letter, ((230 - letter.width) // 2, (230 - letter.height) // 2))
for name, size in [('favicon.png', 64), ('apple-touch-icon.png', 180)]:
    c.resize((size, size), Image.Resampling.LANCZOS).save(PUB / name, optimize=True)
print('pdf assets', len(js) // 1024, 'KB; page fonts',
      [(PUB / 'assets' / 'fonts' / f'lato-{w}.woff2').stat().st_size for w in (400, 700)], 'bytes')
